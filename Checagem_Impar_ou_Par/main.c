#include <stdio.h>
#include <windows.h>
#include <stdlib.h>

//Par ou Impar?


int main(void) {

    SetConsoleOutputCP(65001);
    long long numero_par_ou_impar, resultado;

    //====================================INICIO====================================
    printf("OBS: NÃO coloque um número maior que 9 quintilhões! Ou sofrerá as consequências!\nDigite o numero que deseja saber se é Par ou Ímpar:");
    scanf("%lld", &numero_par_ou_impar);

    resultado = numero_par_ou_impar % 10;

    //====================================RESPOSTA FINAL====================================
    if (resultado == 0 || resultado == 2 || resultado == 4 || resultado == 6 || resultado == 8 ) {
        printf("Seu número é par!\n");
    }
    else {
        printf("Seu número é ímpar!\n");
    }

    system("pause");
    return 0;
}





